GRK_A = [('λόγος', 'لوجوس'), ('θεός', 'ثيوس'), ('ἀγάπη', 'أجاپي'), ('Χριστός', 'خريستوس'), ('ψυχή', 'پسيخي'),
         ('εὐαγγέλιον', 'إيوانجيليون'), ('ἁμαρτία', 'هامارتيا'), ('κρούω', 'كروو')]
GRK_M = [('λόγος', 'لوغوس'), ('θεός', 'ثيوس'), ('ἀγάπη', 'أغاپي'), ('Χριστός', 'خريستوس'), ('βασιλεία', 'ڤاسيليا'),
         ('εὐαγγέλιον', 'إيڤانجيليون'), ('πνεῦμα', 'پنيڤما'), ('ἐκκλησία', 'إككليسيا')]


def check(f, cases):
    bad = [(a, f(a), b) for a, b in cases if f(a) != b]
    return bad


if __name__ == '__main__':
    allbad = check(H, HEB) + check(GA, GRK_A) + check(GM, GRK_M)
    for a, got, want in allbad:
        print('FAIL', a, 'got', got, 'want', want)
    print('ok' if not allbad else f'{len(allbad)} failures')
    sys.exit(1 if allbad else 0)
