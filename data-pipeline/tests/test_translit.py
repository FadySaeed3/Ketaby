    ('דָּוִד', 'دَاوِد'), ('רוּחַ', 'رُوَح'), ('תַּמָּתִי', 'تَمَّاتِي'), ('טַל', 'طَل'), ('קוֹל', 'قُول'),
    ('לֵב', 'لِيڤ'), ('מֶלֶךְ', 'مِلِخ'), ('מִשְׁפָּט', 'مِشْپَاط'), ('חֶסֶד', 'حِسِد'), ('יְהוָה', 'يَهْوَه'),
    ('דּוֹדִי', 'دُودِي'), ('תּוֹרָה', 'تُورَا'), ('עֵר', 'عِير'), ('לָֽיְלָה', 'لَيْلَا'), ('שָׁמַיִם', 'شَامَيِم'),
